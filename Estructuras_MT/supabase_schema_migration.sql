-- Vista 1: Precio de referencia consolidado (prioriza IGMELEC -> GRAPE -> BELLON -> OCHOA)
CREATE OR REPLACE VIEW v_materiales_precio AS
SELECT 
    codigo, 
    descripcion, 
    unidad,
    COALESCE(precio_igmelec, precio_grape, precio_bellon, precio_ochoa, precio_maenca, precio_transdeci) AS precio_referencia
FROM materiales;

-- Vista 2: Costo de materiales por estructura en el análisis detallado
CREATE OR REPLACE VIEW v_costo_por_estructura AS
SELECT 
    estructura, 
    COUNT(*) AS cant_items, 
    ROUND(SUM(subtotal),2) AS costo_materiales_total
FROM analisis_costo_estructura 
WHERE subtotal IS NOT NULL 
GROUP BY estructura;

-- Vista 3: Costo UUCC teórico (usando BOMs y precio base)
CREATE OR REPLACE VIEW v_costo_uucc_por_estructura AS
SELECT 
    u.estructura, 
    COUNT(DISTINCT u.codigo_material) AS materiales_distintos,
    SUM(u.cantidad) AS cantidad_total,
    ROUND(SUM(u.cantidad * COALESCE(m.precio_igmelec, m.precio_grape, 0)), 2) AS costo_materiales_rd
FROM uucc_material_estructura u
LEFT JOIN materiales m ON u.codigo_material = m.codigo
GROUP BY u.estructura 
ORDER BY costo_materiales_rd DESC;

-- Vista 4: Uso total x precio para priorizar compras
CREATE OR REPLACE VIEW v_materiales_uso_total AS
SELECT 
    t.codigo_material,
    m.descripcion,
    t.total AS cantidad_total,
    COALESCE(m.precio_igmelec, m.precio_grape, 0) AS precio_unitario,
    ROUND(t.total * COALESCE(m.precio_igmelec, m.precio_grape, 0), 2) AS costo_total_proyectado
FROM totales_materiales t
JOIN materiales m ON t.codigo_material = m.codigo
ORDER BY costo_total_proyectado DESC;
