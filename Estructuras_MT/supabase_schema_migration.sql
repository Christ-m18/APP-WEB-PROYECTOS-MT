-- TABLA 6: analisis_costo_estructura
CREATE TABLE analisis_costo_estructura (
    id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    estructura      TEXT,
    codigo_material INTEGER REFERENCES materiales(codigo) ON DELETE CASCADE,
    descripcion     TEXT,
    cantidad        NUMERIC,
    unidad          TEXT,
    precio_unitario NUMERIC,
    subtotal        NUMERIC GENERATED ALWAYS AS (
        CASE WHEN cantidad IS NOT NULL AND precio_unitario IS NOT NULL
             THEN ROUND(cantidad * precio_unitario, 2)
             ELSE NULL END
    ) STORED
);

ALTER TABLE analisis_costo_estructura ENABLE ROW LEVEL SECURITY;
CREATE POLICY "Permissive Policy" ON analisis_costo_estructura FOR ALL TO anon, authenticated USING (true) WITH CHECK (true);

