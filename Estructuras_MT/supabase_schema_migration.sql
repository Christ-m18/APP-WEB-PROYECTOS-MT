    descripcion      TEXT NOT NULL,
    unidad           TEXT,
    precio_igmelec   NUMERIC,
    precio_grape     NUMERIC,
    precio_bellon    NUMERIC,
    precio_ochoa     NUMERIC,
    precio_maenca    NUMERIC,
    precio_transdeci NUMERIC
);

